import math
angulo = float(input('Digite o ângulo que você deseja: '))
seno = math.sin(math.radians(angulo))
print('O angule de {} tem o seno de {}'.format(angulo, seno))
cos = math.cos(math.radians(angulo))
print('O angule de {} tem o cosseno de {}'.format(angulo, cos))
tan = math.tan(math.radians(angulo))
print('O angule de {} tem a  de tangente de {}'.format(angulo, tan))
